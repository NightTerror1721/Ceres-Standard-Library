// test_math64.c, node's own Math.* on each double input. The table holds bit patterns, so neither side is read
// through a decimal. The output is committed, so node is only needed to change the sample points.
//
// node's functions are within about an ulp of the truth themselves (V8 carries fdlibm), so the test allows its own
// few ulps plus theirs. erf, erfc, tgamma and lgamma are not in Math: test_math64.c checks them against values
// worked out to 100 digits instead.
