let s = "// Generated by tools/gen_math64_tables.js: double inputs and node's Math.* on them, as bit patterns. Do not edit by hand.\n";
for (const [name, xs] of Object.entries(one)) {
  const fn = name === "exp2" ? (x) => Math.pow(2, x) : Math[name];
  s += `static const unsigned long long t64_${name}[${xs.length}][2] = {\n`;
  for (const x of xs) s += `    { ${bits(x)}, ${bits(fn(x))} },\n`;
  s += "};\n";
}
